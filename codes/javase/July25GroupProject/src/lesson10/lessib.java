package lesson10;

public class lessib {
	public static void main(String[] args) {
		int num = 10;

		System.out.println(num == 10);  
		System.out.println(num != 20);  
		System.out.println(num > 5);    
		System.out.println(num < 20);  
		System.out.println(num >= 10);  
		
		num = 20;

		System.out.println(num == 10);   
		System.out.println(num < 10);   
		System.out.println(num > 30);   
		System.out.println(num <= 10);  
		System.out.println(num != 20);  
	}
}
